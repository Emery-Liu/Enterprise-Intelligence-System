"""
Prompt 模板。

纯字符串拼接函数，不涉及任何LLM调用/网络请求。

约束方式：所有需要结构化输出的prompt，都在末尾明确要求"只返回JSON，
不要有任何多余的文字说明/代码块标记"，配合 llm/client.py 里的
parse_json_response() 做手动解析。
"""

from typing import List


# ---------------------------------------------------------------------------
# 业务摘要 prompt
# 用途：把企业的多源证据浓缩成一段简洁的业务描述文本，
# 该文本会被送去做embedding，用于 retrieval/candidate_generator.py 检索候选分支。
# 输出为自然语言文本，不需要JSON。
# ---------------------------------------------------------------------------
def build_summary_prompt(company: str, evidence_text: str) -> str:
    return f"""你是一位产业研究专家。请根据以下关于企业"{company}"的多源信息，
用一段简洁的中文文字（500字以内）概括该企业真正从事的核心业务和主营产品/技术方向。

要求：
- 只描述企业实际从事的业务，不要复述企业简介中的口号性、宣传性内容。
- 如果多个来源信息有冲突，优先相信专利、项目等能反映真实研发方向的信息。
- 直接输出这段概括文字，不要输出任何其他说明。

企业信息：
{evidence_text}
"""


# ---------------------------------------------------------------------------
# 逐层选择 prompt
# 用途：在产业树上，给定当前父节点及其直接子节点列表，
# 让LLM结合证据判断该企业适用于哪些子节点（支持多选）。
# 输出严格JSON，字段对应 schemas.io_schema.LayerSelection。
# ---------------------------------------------------------------------------
def build_layer_selection_prompt(
    company: str,
    parent_path: List[str],
    children: List[str],
    evidence_text: str,
) -> str:
    parent_path_str = " > ".join(parent_path) if parent_path else "（根节点）"
    children_str = "、".join(children)

    return f"""你是一位产业分类专家。企业"{company}"已经被判断为属于产业分类树中的
"{parent_path_str}"这一分支。现在需要在该分支下，从其直接子类目中选出该企业适用的子类目。

可选的子类目（只能从以下列表中选择，不能自己创造新的类目名称）：
{children_str}

要求：
- 只能选择与企业证据明确相关的子类目，不确定的不要选。
- 企业可能同时涉及多个子类目，允许多选；如果一个都不适用，selected_children返回空列表。
- reasoning必须解释“为什么从当前父节点选择这些子类目”。
- 不要重复描述企业整体业务背景。
- 如果存在多个兄弟子类目，请说明当前选择与企业证据的对应关系。
- 严格按以下JSON格式输出，不要输出任何JSON以外的文字，也不要用```包裹：
{{"parent_path": {parent_path}, "selected_children": ["子类目1", "子类目2"], "reasoning": "简要说明依据"}}

企业信息：
{evidence_text}
"""

# ---------------------------------------------------------------------------
# 路径校验/置信度 prompt（verifier使用）
# 用途：对一条已经生成的完整产业路径，结合证据给出置信度打分和理由。
# 输出严格JSON。
# ---------------------------------------------------------------------------
def build_verifier_prompt(
    company: str,
    path: List[str],
    evidence_text: str,
) -> str:
    path_str = " > ".join(path)

    return f"""你是一位产业分类审核专家。请判断企业"{company}"是否真的适用于以下产业路径：

{path_str}

请结合企业信息给出一个0到1之间的置信度分数（1表示证据非常充分，0表示完全不适用），
并给出简要理由。

严格按以下JSON格式输出，不要输出任何JSON以外的文字，也不要用```包裹：
{{"confidence": 0.0, "reasoning": "简要说明依据"}}

企业信息：
{evidence_text}
"""


# ---------------------------------------------------------------------------
# 单篇文档摘要 prompt
#
# 用途：
# 对单条过长的专利/项目/web/舆情文本进行压缩，
# 避免长文本直接进入后续 evidence_fusion 和企业画像生成。
#
# 输出：
# 自然语言摘要，不需要JSON。
# ---------------------------------------------------------------------------
def build_document_summary_prompt(
    company: str,
    source_type: str,
    text: str,
) -> str:

    return f"""
你是一名产业研究分析专家。

请根据以下关于企业"{company}"的一篇{source_type}资料，
提炼其中与企业产业方向相关的核心信息。

要求：
- 保留企业涉及的技术方向、产品、应用场景、产业领域等关键信息。
- 删除无关内容，例如法律声明、格式信息、重复描述。
- 不要添加原文不存在的信息。
- 摘要长度控制在300字以内。
- 直接输出摘要内容，不要输出标题、解释或其他说明。

文档内容：

{text}
"""